#!/usr/bin/env python3
"""A whole Magento Open Source install, protected vs unprotected, compared request by request.

This is an integration check on a real application, like scripts/framework-smoke.py, but for an
application far too heavy for a workstation: Magento needs MySQL/MariaDB and OpenSearch, and its own
code is tens of thousands of PHP files. .github/workflows/apps.yml prepares it on a GitHub runner
(git clone of the 2.4 release + composer install, setup:install against service containers) and runs:

    python3 scripts/magento-smoke.py --app /path/to/magento --profile bytecode \
        --loader envelock.so --emitter emitter/envelock.so --base-url http://127.0.0.1:8180/

What it does, and why:

- It refuses an install without the marker file `.envelock-smoke-fixture` containing "magento": it
  packs the install in place and issues write requests (a guest cart), so it only touches a
  disposable install.
- Baseline: the cleartext install is served with PHP's built-in server and Magento's own router
  (phpserver/router.php), each probe is requested twice to warm it up (default mode generates
  interceptors, factories and static files on the first requests), then recorded: status, full
  body and headers.
- It packs Magento's OWN code, the whole core: app/code, lib/internal, the entry scripts and every
  .phtml template (PHP that Magento include()s), without the modules' Test/ folders, which never run
  in a shop. vendor/ (third-party libraries) stays cleartext, as recommend advises. The package
  replaces the cleartext files in place; then the generated code and every cache are deleted, so
  Magento regenerates them from the PROTECTED classes. A real extension vendor protects one module
  under app/code; protecting the whole core is the harder case.
- Protected: the same probes, served through the loader with OPcache off, plus bin/magento commands.
- The comparison masks only what differs per request or per process by design: the form key and
  cookie values, CSP nonces, the static-content version stamp, a guest cart's random id and the
  Date/Expires headers. Anything else that differs is reported with its context.

Profiles (--profile): `source` (encryption only), `bytecode` (no PHP source shipped at all) and
`recommended` (what `envelock recommend --source <magento>` turns on for this tree, applied as a user
would). Exit 0 only when every probe returns its expected status and marker and matches the baseline.
"""

from __future__ import annotations

import argparse
import difflib
import http.cookiejar
import json
import os
import pathlib
import re
import shutil
import subprocess  # nosec B404 - runs the local php CLI with fixed argument lists, no shell
import sys
import tempfile
import time
import urllib.error
import urllib.request
import uuid

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "encoder"))
import envelock as a  # noqa: E402

OWN_DIRS = ["app/code", "lib/internal"]
OWN_FILES = ["app/bootstrap.php", "app/autoload.php", "app/functions.php", "pub/index.php",
             "pub/static.php", "pub/get.php", "bin/magento", "phpserver/router.php"]
PHP_EXTENSIONS = {".php", ".phtml"}
SKIP_PARTS = {"Test", "TestFramework"}
# Regenerated by Magento from the classes; deleted before each run so the protected run rebuilds them
# from the protected code instead of reusing what the cleartext run generated.
GENERATED = ["generated/code", "generated/metadata", "var/cache", "var/page_cache", "var/di",
             "var/view_preprocessed", "var/session", "pub/static/frontend", "pub/static/adminhtml",
             "pub/static/_cache", "pub/static/deployed_version.txt"]

# (method, path, body, expected status, marker the response must contain)
PROBES = [
    ("GET", "/", None, 200, b"CMS homepage content goes here"),
    ("GET", "/customer/account/login/", None, 200, b"Customer Login"),
    ("GET", "/customer/account/create/", None, 200, b"Create New Customer Account"),
    ("GET", "/checkout/cart/", None, 200, b"Shopping Cart"),
    ("GET", "/catalogsearch/result/?q=envelock", None, 200, b"Search results for"),
    ("GET", "/contact/", None, 200, b"Contact Us"),
    ("GET", "/envelock-no-such-page", None, 404, b"404 Not Found"),
    ("GET", "/rest/V1/directory/currency", None, 200, b"base_currency_code"),
    ("GET", "/rest/V1/directory/countries/US", None, 200, b"United States"),
    ("POST", "/rest/V1/guest-carts", b"", 200, None),
    ("POST", "/graphql", b'{"query":"{ storeConfig { store_name base_currency_code locale } }"}', 200,
     b"storeConfig"),
    ("GET", "/admin/", None, 200, b"sign in"),
]
CLI = [["--version"], ["module:status", "--enabled"], ["cache:status"]]

FLAG_KWARGS = {"--encode-strings": "encode_strings", "--obfuscate": "obfuscate",
               "--obfuscate-flow": "obfuscate_flow", "--obfuscate-methods": "obfuscate_methods",
               "--include-protection": "include_protection", "--no-ffi": "no_ffi",
               "--no-prepend": "no_prepend", "--strip-comments": "strip_comments", "--compact": "compact",
               "--sealed": "sealed", "--bytecode": "bytecode"}

_MASKS = [
    (re.compile(rb'nonce="[^"]*"'), b'nonce="<NONCE>"'),
    (re.compile(rb"'nonce-[^']*'"), b"'nonce-<NONCE>'"),
    (re.compile(rb"version\d{6,}"), b"version<STAMP>"),
    (re.compile(rb'(name=\\?"form_key\\?"[^>]*?value=\\?")[A-Za-z0-9]{16}'), rb"\1<FORM_KEY>"),
    (re.compile(rb'("form_?[kK]ey\\?"\s*:\s*\\?")[A-Za-z0-9]{16}'), rb"\1<FORM_KEY>"),
    (re.compile(rb"(/form_key/)[A-Za-z0-9]{16}"), rb"\1<FORM_KEY>"),
    # The admin: its URLs carry a per-session secret key, its pages the session's form key, and the
    # page states the server's clock.
    (re.compile(rb"(/key/)[0-9a-f]{64}"), rb"\1<ADMIN_KEY>"),
    (re.compile(rb"(FORM_KEY\s*=\s*')[A-Za-z0-9]{16}"), rb"\1<FORM_KEY>"),
    (re.compile(rb"(serverTimezoneSeconds:\s*)\d+"), rb"\1<CLOCK>"),
    # The captcha configuration states when the page was made.
    (re.compile(rb'("timestamp\\?"\s*:\s*)\d{9,}'), rb"\1<CLOCK>"),
]
# Magento gives some elements a random id on every render (id="idQ8Zu4JfG"): each value is learnt
# from the page itself and replaced wherever the page uses it, never by a broad pattern that could
# also hide a real word.
_RANDOM_ID = re.compile(rb'id="(id[A-Za-z0-9]{8})"')


def mask_body(path: str, payload: bytes, secrets: list[str]) -> bytes:
    for value in secrets:
        if len(value) >= 8:
            payload = payload.replace(value.encode(), b"<COOKIE>")
    for random_id in set(_RANDOM_ID.findall(payload)):
        payload = payload.replace(random_id, b"id<RANDOM>")
    for pattern, replacement in _MASKS:
        payload = pattern.sub(replacement, payload)
    if path == "/rest/V1/guest-carts":
        payload = re.sub(rb'^"[A-Za-z0-9]{32}"$', b'"<MASKED_CART_ID>"', payload)
    return payload


def mask_headers(headers) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for name, value in headers.items():
        key = name.lower()
        if key in ("date", "expires", "last-modified"):
            continue
        if key == "set-cookie":
            cookie, _, attributes = value.partition(";")
            cookie_name = cookie.split("=", 1)[0]
            attributes = re.sub(r"(?i)(expires=)[^;]*", r"\1<CLOCK>", attributes)
            value = f"{cookie_name}=<VALUE>;{attributes}"
        elif key.startswith("content-security-policy"):
            value = re.sub(r"'nonce-[^']*'", "'nonce-<NONCE>'", value)
        out.setdefault(key, []).append(value)
    return out


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, request, fp, code, msg, headers, newurl):
        return None


def fetch(opener, base: str, method: str, path: str, body: bytes | None, timeout: int):
    request = urllib.request.Request(base.rstrip("/") + path, data=body, method=method,
                                     headers={"Content-Type": "application/json",
                                              "Accept": "application/json" if path.startswith(("/rest", "/graphql"))
                                              else "text/html"})
    try:
        with opener.open(request, timeout=timeout) as response:
            return response.status, response.read(), response.headers
    except urllib.error.HTTPError as error:
        return error.code, error.read(), error.headers
    except Exception as error:  # noqa: BLE001 - a connection failure is a result, not a crash
        return -1, repr(error).encode("utf-8", errors="backslashreplace"), None


def probe(base: str) -> dict:
    """Warm each probe twice, then record it; one browser-like cookie jar for the whole run."""
    jar = http.cookiejar.CookieJar()
    opener = urllib.request.build_opener(_NoRedirect(), urllib.request.HTTPCookieProcessor(jar))
    results = {}
    for index, (method, path, body, _code, _marker) in enumerate(PROBES):
        started = time.monotonic()
        for _ in range(2):
            fetch(opener, base, method, path, body, timeout=900)
        warm = time.monotonic() - started
        started = time.monotonic()
        status, payload, headers = fetch(opener, base, method, path, body, timeout=900)
        took = time.monotonic() - started
        secrets = [cookie.value for cookie in jar if cookie.value]
        results[f"{index:02d} {method} {path}"] = {
            "status": status, "raw": payload,
            "body": mask_body(path, payload, secrets),
            "headers": mask_headers(headers) if headers is not None else {},
            "seconds": (round(warm, 2), round(took, 2)),
        }
    return results


def check_expectations(label: str, results: dict) -> list[str]:
    problems = []
    for index, (method, path, _body, code, marker) in enumerate(PROBES):
        item = results[f"{index:02d} {method} {path}"]
        if item["status"] != code:
            problems.append(f"{label}: {method} {path} -> HTTP {item['status']}, expected {code}: "
                            f"{item['raw'][:300]!r}")
        elif marker is not None and marker.lower() not in item["raw"].lower():
            problems.append(f"{label}: {method} {path} lacks {marker!r}: {item['raw'][:300]!r}")
    return problems


def clear_generated(app: pathlib.Path) -> None:
    for relative in GENERATED:
        target = app / relative
        if target.is_dir():
            shutil.rmtree(target)
            target.mkdir(parents=True, exist_ok=True)
        elif target.exists():
            target.unlink()


def write_ini(directory: pathlib.Path, loader: pathlib.Path | None, identity: pathlib.Path | None,
              sealed_cleartext: list[str] | None) -> pathlib.Path:
    directory.mkdir(parents=True, exist_ok=True)
    lines = ["memory_limit=4G", "max_execution_time=0", "opcache.enable=0", "opcache.enable_cli=0",
             "enable_dl=0", "ffi.enable=0", "variables_order=EGPCS"]
    if loader is not None:
        lines += [f"extension={loader.as_posix()}", f"envelock.identity={identity.as_posix()}"]
    if sealed_cleartext:
        lines.append("envelock.sealed_cleartext=" + os.pathsep.join(sealed_cleartext))
    (directory / "zz-envelock.ini").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return directory


def serve(app: pathlib.Path, port: int, ini: pathlib.Path, php: str, log: pathlib.Path) -> subprocess.Popen:
    environment = dict(os.environ, PHP_INI_SCAN_DIR=f"{os.pathsep}{ini}")
    with open(log, "wb") as handle:
        process = subprocess.Popen([php, "-S", f"127.0.0.1:{port}", "-t", "pub", "phpserver/router.php"],  # nosec B603
                                   cwd=app, env=environment, stdout=handle, stderr=handle)
    deadline = time.monotonic() + 60
    marker = f"Development Server (http://127.0.0.1:{port}) started"
    while time.monotonic() < deadline:
        if process.poll() is not None:
            raise SystemExit(f"the server exited at start:\n{log.read_text(errors='replace')[-3000:]}")
        if marker in log.read_text(errors="replace"):
            return process
        time.sleep(0.2)
    process.terminate()
    raise SystemExit(f"the server did not start on port {port}")


def run_cli(app: pathlib.Path, ini: pathlib.Path, php: str) -> dict:
    environment = dict(os.environ, PHP_INI_SCAN_DIR=f"{os.pathsep}{ini}")
    out = {}
    for command in CLI:
        result = subprocess.run([php, "bin/magento", *command], cwd=app, env=environment,  # nosec B603
                                capture_output=True, timeout=900, check=False)
        out[" ".join(command)] = (result.returncode, result.stdout, result.stderr[-2000:])
    return out


def own_files(app: pathlib.Path) -> list[pathlib.Path]:
    files = []
    for relative in OWN_DIRS:
        for path in sorted((app / relative).rglob("*")):
            rel = path.relative_to(app)
            if (path.is_file() and not path.is_symlink() and path.suffix.lower() in PHP_EXTENSIONS
                    and not SKIP_PARTS.intersection(rel.parts)):
                files.append(rel)
    files += [pathlib.Path(f) for f in OWN_FILES if (app / f).is_file()]
    return files


def recommended_kwargs(app: pathlib.Path) -> tuple[dict, set[str], dict]:
    """What `envelock recommend --source <magento>` turns on, as pack_tree arguments, plus the files
    it says to keep cleartext."""
    recommendation = a.recommend_options(app, PHP_EXTENSIONS | {""})
    unknown = [flag for flag in recommendation["on"] if flag not in FLAG_KWARGS]
    if unknown:
        raise SystemExit(f"recommend turned on flags this check does not map: {unknown}")
    keep = {name for files in recommendation.get("exclude", {}).values() for name in files}
    return {FLAG_KWARGS[flag]: True for flag in recommendation["on"]}, keep, recommendation


def show_difference(key: str, expected: dict, actual: dict) -> None:
    print(f"  DIF  {key}: HTTP {expected['status']} -> {actual['status']}")
    if expected["headers"] != actual["headers"]:
        for name in sorted(set(expected["headers"]) | set(actual["headers"])):
            if expected["headers"].get(name) != actual["headers"].get(name):
                print(f"       header {name}: {expected['headers'].get(name)} -> {actual['headers'].get(name)}")
    if expected["body"] != actual["body"]:
        # The differing fragments with some context, not whole lines: Magento puts kilobytes of JSON
        # on one line, and a truncated line hides the very difference it is shown for.
        before, after = expected["body"].splitlines(), actual["body"].splitlines()
        shown = 0
        for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, before, after, autojunk=False).get_opcodes():
            if op == "equal":
                continue
            old, new = b"\n".join(before[i1:i2]), b"\n".join(after[j1:j2])
            for cop, a1, a2, b1, b2 in difflib.SequenceMatcher(None, old[:40000], new[:40000],
                                                                autojunk=False).get_opcodes():
                if cop == "equal":
                    continue
                print(f"       line {i1 + 1} {cop}: ...{old[max(0, a1 - 70):a1]!r} "
                      f"[{old[a1:a2][:120]!r} -> {new[b1:b2][:120]!r}]")
                shown += 1
                if shown >= 12:
                    print("       (more differences not shown)")
                    return


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--app", type=pathlib.Path, required=True)
    parser.add_argument("--profile", choices=("source", "bytecode", "recommended"), required=True)
    parser.add_argument("--loader", type=pathlib.Path, required=True, help="Loader the protected shop runs with")
    parser.add_argument("--emitter", type=pathlib.Path,
                        help="Pack-time build with envelock_bc_emit (bytecode profiles)")
    parser.add_argument("--php", default="php")
    parser.add_argument("--base-url", default="http://127.0.0.1:8180/")
    parser.add_argument("--report", type=pathlib.Path, help="Write a JSON summary here")
    arguments = parser.parse_args()

    app = arguments.app.resolve()
    marker = app / ".envelock-smoke-fixture"
    if not marker.is_file() or marker.read_text(encoding="utf-8").strip() != "magento":
        raise SystemExit("fixture marker missing or wrong: this check packs the install in place")
    port = int(arguments.base_url.rstrip("/").rsplit(":", 1)[1])
    php = arguments.php
    work = pathlib.Path(tempfile.mkdtemp(prefix="envelock-magento-"))
    summary: dict = {"profile": arguments.profile}

    clear_generated(app)
    # The packing plan is made from the tree as shipped, before any run generates code into it.
    files = own_files(app)
    # What `pack` does by default on the command line: a signed manifest, enforced at run time.
    kwargs: dict = {"manifest": True, "enforce_manifest": True}
    keep: set[str] = set()
    if arguments.profile == "bytecode":
        kwargs["bytecode"] = True
    elif arguments.profile == "recommended":
        flags, keep, recommendation = recommended_kwargs(app)
        kwargs.update(flags)
        summary["recommend_on"] = recommendation["on"]
        summary["recommend_off"] = recommendation.get("off", {})
        summary["recommend_keep_cleartext"] = sorted(keep)
        print("recommend:", " ".join(recommendation["on"]))
        for flag, reason in recommendation.get("off", {}).items():
            print(f"  off {flag}: {reason[:200]}")
        for category, names in recommendation.get("exclude", {}).items():
            print(f"  keep cleartext ({category}): {len(names)} files, e.g. {names[:3]}")
    files = [f for f in files if f.as_posix() not in keep]
    if kwargs.get("bytecode"):
        if arguments.emitter is None:
            raise SystemExit("a bytecode profile needs --emitter (a build with --enable-envelock-bcemit)")
        kwargs.update(bytecode_loader=str(arguments.emitter.resolve()), deploy_root=app)

    plain_ini = write_ini(work / "ini-plain", None, None, None)
    server = serve(app, port, plain_ini, php, work / "baseline.log")
    try:
        expected = probe(arguments.base_url)
    finally:
        server.terminate()
        server.wait(timeout=60)
    expected_cli = run_cli(app, plain_ini, php)
    problems = check_expectations("unprotected", expected)
    if problems:
        print("\n".join(problems))
        print("--- unprotected server log (tail) ---")
        print((work / "baseline.log").read_text(errors="replace")[-4000:])
        raise SystemExit("the UNPROTECTED shop does not pass the probes: fix the install, not the protector")

    # The cleartext files leave the install BEFORE packing: bytecode is compiled at each file's deploy
    # path and the packer refuses to overwrite a file already there.
    own = work / "own"
    for relative in files:
        target = own / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(app / relative, target)
        (app / relative).unlink()
    print(f"packing {len(files)} files ({sum((own / f).stat().st_size for f in files) / 1e6:.1f} MB) with "
          + ", ".join(sorted(k for k, v in kwargs.items() if v is True)), flush=True)
    owner = a.make_owner()
    recipient = a.make_recipient("magento-smoke")
    identity = work / "identity.bin"
    identity.write_bytes(a.identity_bundle_bytes([a.make_identity(recipient, owner)]))
    os.chmod(identity, 0o600)
    started = time.monotonic()
    info = a.pack_tree(own, work / "packed", [a.recipient_public(recipient)], owner, str(uuid.uuid4()),
                       extensions=PHP_EXTENSIONS | {""}, php=php, target_os="linux", **kwargs)
    summary["pack_seconds"] = round(time.monotonic() - started, 1)
    summary["protected_files"] = info["protected_files"]
    print(f"packed {info['protected_files']} files in {summary['pack_seconds']} s", flush=True)
    for source in (work / "packed").rglob("*"):
        if source.is_file():
            target = app / source.relative_to(work / "packed")
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)

    sealed = None
    if kwargs.get("sealed"):
        sealed = [str(app / d) for d in ("vendor", "generated", "app/etc", "var", "setup", "dev")]
    guarded_ini = write_ini(work / "ini-protected", arguments.loader.resolve(), identity, sealed)
    clear_generated(app)
    server = serve(app, port, guarded_ini, php, work / "protected.log")
    try:
        actual = probe(arguments.base_url)
    finally:
        server.terminate()
        server.wait(timeout=60)
    actual_cli = run_cli(app, guarded_ini, php)

    failures = check_expectations("protected", actual)
    differing = []
    for key in expected:
        same = all(expected[key][part] == actual[key][part] for part in ("status", "body", "headers"))
        print(("  OK   " if same else "  DIF  ") + key + f"  ->  {actual[key]['status']}  "
              f"(s: unprotected {expected[key]['seconds']}, protected {actual[key]['seconds']})")
        if not same:
            differing.append(key)
            show_difference(key, expected[key], actual[key])
    for command, before in expected_cli.items():
        after = actual_cli[command]
        same = before[:2] == after[:2]
        print(("  OK   " if same else "  DIF  ") + f"bin/magento {command} -> exit {after[0]}")
        if not same:
            differing.append(f"bin/magento {command}")
            print(f"       unprotected: {before[1][-600:]!r} {before[2][-400:]!r}")
            print(f"       protected  : {after[1][-600:]!r} {after[2][-400:]!r}")
    if failures:
        print("\n".join(failures))
        print("--- protected server log (tail) ---")
        print((work / "protected.log").read_text(errors="replace")[-4000:])
    summary.update(differing=differing, failures=failures,
                   probes=len(expected) + len(expected_cli))
    if arguments.report:
        arguments.report.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    total = len(expected) + len(expected_cli)
    verdict = "IDENTICAS" if not differing and not failures else f"DIFIEREN en {len(differing)}"
    print(f"magento ({arguments.profile}): {total - len(differing)}/{total} respuestas identicas — {verdict}")
    return 0 if not differing and not failures else 1


if __name__ == "__main__":
    raise SystemExit(main())
